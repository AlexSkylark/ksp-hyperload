// Generates src/TMinus/Profiler/Hooks/HarmonyCallSlots.g.cs: the pool of stub
// classes that HarmonyCallHooks patches around other mods' patches, one Outer
// and one Inner class per slot (docs/m5-profiler-plan.md, "Step 4b").
//
// Why generated classes: a Harmony patch method must be a real, non-generic
// method (Harmony serializes patch info and resolves patch methods by token),
// and __state is one local per patch class. So each bracketed method needs its
// own pair of classes, known at compile time.
//
// Run with: node tools/codegen/harmony-call-slots.mjs [slots]
// Slot 0 is the calibration target's; slots 1..N are handed out to methods.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const slots = Number(process.argv[2] ?? 1024);
if (!Number.isInteger(slots) || slots < 1) throw new Error(`slots: expected a positive whole number, got ${process.argv[2]}`);

const out = join(dirname(fileURLToPath(import.meta.url)), "../../src/TMinus/Profiler/Hooks/HarmonyCallSlots.g.cs");

const lines = [
  "// <auto-generated>",
  "// Generated by tools/codegen/harmony-call-slots.mjs; do not edit. Regenerate to change the pool size.",
  "// </auto-generated>",
  "",
  "using System;",
  "",
  "namespace TMinus.Profiler.Hooks.CallSlots",
  "{",
  "    internal static class Pool",
  "    {",
  `        /// <summary>Slots, calibration slot 0 included.</summary>`,
  `        public const int Size = ${slots + 1};`,
  "",
  "        public static Type Outer(int slot) => typeof(Pool).Assembly.GetType(typeof(Pool).Namespace + \".O\" + slot, true);",
  "        public static Type Inner(int slot) => typeof(Pool).Assembly.GetType(typeof(Pool).Namespace + \".I\" + slot, true);",
  "    }",
  "",
];
for (let i = 0; i <= slots; i++) {
  lines.push(`    internal static class O${i} { private static void Prefix(out long __state) => __state = ProfilerClock.Now(); private static void Postfix(long __state) => HarmonyCallHooks.Outer(${i}, __state); }`);
  lines.push(`    internal static class I${i} { private static void Prefix(out long __state) => __state = ProfilerClock.Now(); private static void Postfix(long __state) => HarmonyCallHooks.Inner(${i}, __state); }`);
}
lines.push("}", "");

writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${slots} slots plus calibration`);
